type Pattern = [RegExp, (match: RegExpMatchArray) => string];

const chineseSuffix = (value: string, suffix: string): string =>
  /[A-Za-z0-9]$/.test(value.trim()) ? `${value.trim()} ${suffix}` : `${value.trim()}${suffix}`;
const chinesePrefix = (prefix: string, value: string): string =>
  `${prefix}${/^[A-Za-z0-9]/.test(value.trim()) ? ' ' : ''}${value.trim()}`;

const translateSchedulePhrase = (value: string): string => {
  const days: Record<string, string> = { Sun: '周日', Mon: '周一', Tue: '周二', Wed: '周三', Thu: '周四', Fri: '周五', Sat: '周六' };
  const months: Record<string, string> = { Jan: '1月', Feb: '2月', Mar: '3月', Apr: '4月', May: '5月', Jun: '6月', Jul: '7月', Aug: '8月', Sep: '9月', Oct: '10月', Nov: '11月', Dec: '12月' };
  return value
    .replace(/\b(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\s+(\d{1,2})\b/g, (_, month, day) => `${months[month as string]}${day}日`)
    .replace(/\b(Sun|Mon|Tue|Wed|Thu|Fri|Sat)\b/g, day => days[day])
    .replace(/\b(\d{1,2}:\d{2})\s*AM\b/gi, '上午 $1')
    .replace(/\b(\d{1,2}:\d{2})\s*PM\b/gi, '下午 $1')
    .replace(/^once, /i, '一次，')
    .replace(/^once$/i, '一次')
    .replace(/^every weekday at /i, '每个工作日 ')
    .replace(/^every day at /i, '每天 ')
    .replace(/^weekly \(pick days\)$/i, '每周（请选择星期）')
    .replace(/, each when the previous step succeeds\./gi, '，每一步都在上一步成功时执行。')
    .replace(/, each when the previous step ends\./gi, '，每一步都在上一步结束时执行。')
    .replace(/\bthe next time\b/gi, '下一次')
    .replace(/\bevery time\b/gi, '每次')
    .replace(/\bsucceeds\b/gi, '成功时')
    .replace(/\bfinishes\b/gi, '完成时')
    .replace(/\bright away\b/gi, '立即')
    .replace(/· next:/gi, '· 下次：')
    .replace(/· stops after (\d+) runs?/gi, '· 运行 $1 次后停止')
    .replace(/, then /gi, '，然后 ')
    .replace(/：\s+/g, '：');
};

